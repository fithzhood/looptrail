function startingDeck() {
  // 10 cards, randomized each run: 4 clockwise-only, 4 counterclockwise-only, 2 free
  const values = shuffle([1, 2, 2, 3, 3, 3, 3, 4, 4, 5]);
  return values.map((v, i) => {
    const c = { value: v };
    if (i < 4) c.dir = 1;
    else if (i < 8) c.dir = -1;
    return c;
  });
}

